void gpu_port_demo_task_init(int gpu_out_format)
{
    //创建任务链
    __this->gpu_task_head = jlgpu_create_task_list_head();
    if (!__this->gpu_task_head) {
        printf("<gpu_port_demo> gpu create task list head fail!!! ");
        return;
    }

    //设置任务链输出的格式
    jlgpu_set_task_list_out_format(__this->gpu_task_head, gpu_out_format);

}

void gpu_port_demo_task_free(void)
{
    if (__this->gpu_task_head) {
        //删除任务链
        jlgpu_delete_task_list_head(__this->gpu_task_head);
        __this->gpu_task_head = NULL;
    }
}

void gpu_port_demo_create_task(int width, int height, int left, int top, u32 color)
{
    struct rect draw_rect = {0};

    draw_rect.left	 = left;
    draw_rect.top	 = top;
    draw_rect.width  = width;
    draw_rect.height = height;

    u8 a = (color >> 24) & 0xff;
    u8 r = (color >> 16) & 0xff;
    u8 g = (color >> 8) & 0xff;
    u8 b = color & 0xff;
    jlgpu_task_fill_param_init(0, 0, a, r, g, b);

    //创建gpu绘制任务
    memcpy(&task_param.draw, &draw_rect, sizeof(struct rect));
    printf("task_param :%d * %d * %d * %d\n", task_param.draw.left, task_param.draw.top, task_param.draw.width, task_param.draw.height);
    jlgpu_get_win_rect(&task_param.area);	// 限制区域是整个GPU窗口区域
    jlgpu_create_task(__this->gpu_task_head, &task_param);
}

void gpu_port_demo_color_fill(int width, int height, int left, int top, u32 color)
{
    //根据实际情况申请内存空间
    int out_bpp = gpu_get_format_bpp(__this->gpu_task_head->out_param.format);
    int out_stride = width * out_bpp / 8;
    __this->buf1 = (uint8_t *)zalloc(block_buffer_height * out_stride);
    __this->buf2 = (uint8_t *)zalloc((height % block_buffer_height) * out_stride);

    //计算出总共需要多少个block
    int block_num = 0;
    block_num = (height % block_buffer_height) ? (height / block_buffer_height + 1) : (height / block_buffer_height);
    printf("<%s> block_num:%d\n", __func__, block_num);

    gpu_port_demo_create_task(width, height, left, top, color);

    //设置输出buf并且显示到屏幕上
    lcd_set_draw_area(left, width + left - 1, top, height + top - 1);
    struct rect draw_rect = {0};
    for (int i = 0; i < block_num; i++) {
        draw_rect.left	 = left;
        draw_rect.top	 = top + i * block_buffer_height;
        draw_rect.width  = width;

        if ((i == block_num - 1) && (height % block_buffer_height)) {
            draw_rect.height = height % block_buffer_height;
        } else {
            draw_rect.height = block_buffer_height;
        }
        jlgpu_set_task_list_out_buf(__this->gpu_task_head,  __this->buf1, &draw_rect, 0, 0);
        jlgpu_task_list_run(__this->gpu_task_head);
        if (!i) {
            /* 开始推屏时使用 kistart */
            lcd_draw_kistart(__this->buf1, draw_rect.left, draw_rect.left + draw_rect.width - 1, draw_rect.top, draw_rect.top + draw_rect.height - 1);
            lcd_wait_busy();
        } else {
            /* 之后推屏时使用 continue 续传 */
            lcd_draw_continue(__this->buf1, draw_rect.left, draw_rect.left + draw_rect.width - 1, draw_rect.top, draw_rect.top + draw_rect.height - 1);
            lcd_wait_busy();
        }
    }

    lcd_wait_busy();
    //将申请的内存进行释放
    if (__this->buf1) {
        free(__this->buf1);
        __this->buf1 = NULL;
    }
    if (__this->buf2) {
        free(__this->buf2);
        __this->buf2 = NULL;
    }
}

