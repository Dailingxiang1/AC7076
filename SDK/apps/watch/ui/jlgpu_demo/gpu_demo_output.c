/**
 * @brief gpu_demo_output_mode_test gpu输出格式demo
 *
 * @param head
 * @param output_mode
 */
/* ------------------------------------------------------------------------------------*/
static void gpu_demo_output_mode_test(pJLGPUTaskHead_t head, int output_mode)
{
    //创建一个tmp链表头，输出不同格式的gpu数据
    struct rect draw_rect = {0, 0, 52, 52};
    JLGPUTaskHead_t tmp_head = {
        .win_rect.left = 0,
        .win_rect.top = 0,
        .win_rect.width = 320,
        .win_rect.height = 386,
    };
    //配置输出格式
    jlgpu_set_task_list_out_format(&tmp_head, output_mode);
    //配置输出区域
    jlgpu_set_task_list_out_buf(&tmp_head, tmpbuf_50x50, &draw_rect, 0, 0);
    //合成背景到tmpbuf
    JLGPUTaskParam_t dst_param = {
        .task_type = GPU_TASK_IMAGE,
        .task_id = 0x1,
        .element_id = 0x0,
        .format  = GPU_FORMAT_A8,
        .global_alpha = 128,
        .image.width = 50,
        .image.height = 50,
        .texture.data = (u8 *)test_image_a8,
        .alpha = 100,
        .red  = 0xff,
    };
    //配置图像坐标
    dst_param.draw.left = 0;
    dst_param.draw.top = 0;
    dst_param.draw.width = dst_param.image.width;
    dst_param.draw.height = dst_param.image.height;
    jlgpu_get_win_rect(&dst_param.area);
    //注意图像的宽高需要与输出格式对齐（向0对齐），这里为了方便展示统一取8对齐
    dst_param.area.width = dst_param.image.width / 8 * 8;
    //添加背景任务
    jlgpu_update_task_by_id(&tmp_head, dst_param.task_id, dst_param.element_id, &dst_param);
    //启动合成
    /* jlgpu_dump_all_task(&tmp_head,__func__,__LINE__); */
    jlgpu_task_list_run(&tmp_head);
    //释放tmp链表
    void jlgpu_free_all_task(pJLGPUTaskHead_t head);
    jlgpu_free_all_task(&tmp_head);


    gpu_demo_output_mode_show(head, output_mode);

}
