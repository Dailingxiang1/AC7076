static void demo_lcd_flush_finish_cb(int err)
{
    IO_DBI_LOW();
    if (__this->buffer_hdl) {
        set_buffer_idle(__this->buffer_hdl, __this->buffer_adr);
        __this->buffer_adr = NULL;
        os_sem_post(&__this->buffer_sem);	// 每推完一个分块，发送一个buf信号量
    }
}

//双buf推屏初始化
static void demo_lcd_dual_buf_init(void)
{
    os_sem_create(&__this->buffer_sem, 1);
    lcd_draw_set_callback(demo_lcd_flush_finish_cb);			// 设置lcd推屏结束回调
}

static void demo_lcd_flush_buffer_start(void *buf_hdl, void *buf_adr, struct rect *rect, int is_continue)
{
    int x_start = rect->left;
    int x_end = x_start + rect->width - 1;
    int y_start = rect->top;
    int y_end = y_start + rect->height - 1;

    IO_DBI_HIGH();

    int os_err = os_sem_pend(&__this->buffer_sem, 100);	// 等待上一个分块推完
    if (os_err) {
        ASSERT(0, "%s os_err:%d\n", __func__, os_err);
    }
    /* put_buf(buf_adr, (x_end - x_start) * 2); */
    set_buffer_used(buf_hdl, buf_adr);	// 设置buf状态
    __this->buffer_adr = buf_adr;

    if (!is_continue) {
        lcd_draw_kistart(buf_adr, x_start, x_end, y_start, y_end);	// DBI kistart
    } else {
        lcd_draw_continue(buf_adr, x_start, x_end, y_start, y_end);	// DBI 续传
    }
}

void gpu_port_demo_task_init(int gpu_out_format)
{
    //创建任务链
    __this->gpu_task_head = jlgpu_create_task_list_head();
    if (!__this->gpu_task_head) {
        printf("<gpu_port_demo> gpu create task list head fail!!! ");
        return;
    }

    //设置任务链输出的格式
    jlgpu_set_task_list_out_format(__this->gpu_task_head, gpu_out_format);
}

void gpu_port_demo_task_free(void)
{
    if (__this->gpu_task_head) {
        //删除任务链
        jlgpu_delete_task_list_head(__this->gpu_task_head);
        __this->gpu_task_head = NULL;
    }
}


