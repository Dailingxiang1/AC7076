//创建绘制背景颜色任务
static void gpu_port_demo_create_bg_task(struct rect draw_rect, u32 color)
{
    u8 a = (color >> 24) & 0xff;
    u8 r = (color >> 16) & 0xff;
    u8 g = (color >> 8) & 0xff;
    u8 b = (color) & 0xff;

    //创建gpu绘制任务
    jlgpu_task_fill_param_init(0, 0, a, r, g, b);
    memcpy(&task_param.draw, &draw_rect, sizeof(struct rect));
    jlgpu_get_win_rect(&task_param.area);	// 限制区域是整个GPU窗口区域

    printf("<%s>----param->head:0x%p\n", __func__, __this->gpu_task_head);

    jlgpu_create_task(__this->gpu_task_head, &task_param);
}

//创建绘制图片的任务
static void gpu_port_demo_create_jlimg_task(struct img_info_jl *imgjl)
{
    //打开资源文件
    UI_RESFILE *fp =  res_fopen(imgjl->path, "r");
    if (!fp) {
        printf("%s fp is null", __func__);
        ASSERT(0);
    }
    //获取文件的flash table
    struct flash_file_info file_info;
    ui_res_flash_info_get(&file_info, imgjl->path, "res", true);
    jlgpu_task_texture_param_init(0, 0);
    //获取图片信息
    int err = jlui_res_get_image_info(0, (imgjl->image_id & 0xffff), fp, &task_param.image, &task_param.info);
    if (err) {
        ASSERT(0);
    }
    printf("<%s>--------format:%d, offset:0x%x\n", __func__, task_param.image.format, task_param.image.offset);

    if ((task_param.image.format == PIXEL_FMT_AL88)
        || (task_param.image.format == PIXEL_FMT_AL44)
        || (task_param.image.format == PIXEL_FMT_AL22)
        || (task_param.image.format == PIXEL_FMT_L8)
        || (task_param.image.format == PIXEL_FMT_L4)
        || (task_param.image.format == PIXEL_FMT_L2)
        || (task_param.image.format == PIXEL_FMT_L1)
        || (task_param.image.format == PIXEL_FMT_A8)
        || (task_param.image.format == PIXEL_FMT_A4)
        || (task_param.image.format == PIXEL_FMT_A2)
        || (task_param.image.format == PIXEL_FMT_A1)
       ) {
        int tab_size = get_clut_format_tabsize(task_param.image.format, task_param.image.clut_format);
        task_param.image.offset += tab_size;
        task_param.image.len -= tab_size;
    }
    ui_res_get_image_flash_info(&task_param.info, &file_info, &task_param.image);

    printf("<%s>--------format:%d, offset:0x%x\n", __func__, task_param.image.format, task_param.info.offset);

    printf("<%s>--------size:%d * %d\n", __func__, task_param.image.width, task_param.image.height);

    task_param.draw.width = task_param.image.width;
    task_param.draw.height = task_param.image.height;
    task_param.draw.left = imgjl->left;
    task_param.draw.top = imgjl->top;
    jlgpu_get_win_rect(&task_param.area);	// 限制区域是整个GPU窗口区域

    if (task_param.image.format == PIXEL_FMT_JPEG) {
        //暂未处理
    } else {
        task_param.format = res_format_to_gpu(task_param.image.format);
        task_param.task_type = GPU_TASK_IMAGE;
    }

    task_param.clut_format = task_param.image.clut_format;
    task_param.has_clut = task_param.image.has_clut;
    task_param.texture.data = (u8 *)task_param.info.offset;
    task_param.texture.mmu_tab_base = (u8 *)task_param.info.tab;

    printf("<%s>--------format:%d, offset:0x%08x\n", __func__, task_param.image.format, (u32)task_param.texture.data);
    //配置图片旋转参数
    if (imgjl->rotate_en) {
        task_param.rotate_en = 1;
        task_param.texture.tran.rotate_cx = imgjl->rotate_cx;	//图片旋转中心(这里的坐标是相对于图片而不是相对于屏幕)
        task_param.texture.tran.rotate_cy = imgjl->rotate_cy;
        task_param.texture.tran.rotate_dx = imgjl->rotate_dx;	//旋转之后中心点的坐标
        task_param.texture.tran.rotate_dy = imgjl->rotate_dy;
        task_param.texture.tran.rotate_angle = imgjl->rotate_angle;
    }

    //配置图片缩放参数
    if (imgjl->scale_en) {
        task_param.scale_en = 1;
        task_param.texture.tran.ratio_w = imgjl->ratio_w;		//宽的缩放倍数
        task_param.texture.tran.ratio_h = imgjl->ratio_h;		//高的缩放倍数
    }

    jlgpu_create_task(__this->gpu_task_head, &task_param);

    if (fp) {
        res_fclose(fp);
    }
}

void gpu_port_demo_draw_jlimage(struct img_info_jl *imgjl, u32 background)
{
    //输出配置
    int width = __this->info.width;
    int height = __this->info.height;
    int out_format = GPU_FORMAT_RGB565;
    int out_bpp = gpu_get_format_bpp(out_format) / 8;
    int out_stride = width * out_bpp;
    int block_height = 16;		//分块输出到屏幕上，每块的大小（width * block_height）

    //申请输出的缓存空间
    __this->buf1 = (uint8_t *)zalloc(block_height * out_stride);
    __this->buf2 = (uint8_t *)zalloc((height % block_height) * out_stride);

    struct rect draw_task_rect = {0};
    //创建绘制背景颜色的任务
    if (background) {
        draw_task_rect.left = 0;
        draw_task_rect.top = 0;
        draw_task_rect.width = __this->info.width;
        draw_task_rect.height = __this->info.height;
        gpu_port_demo_create_bg_task(draw_task_rect, background);
    }

    //创建绘制图片的任务
    gpu_port_demo_create_jlimg_task(imgjl);

    //设置输出buf并且显示到屏幕上
    int block_num = 0;
    block_num = (height % block_height) ? (height / block_height + 1) : (height / block_height);
    //设置推屏区域
    lcd_set_draw_area(0, width - 1, 0, height - 1);

    struct rect draw_rect = {0};
    int draw_height;
    for (int i = 0; i < block_num; i++) {
        if ((i + 1) * block_height < height) {
            draw_height = block_height;
        } else {
            draw_height = height - (i * block_height);
        }

        draw_rect.left	 = 0;
        draw_rect.top	 = i * block_height;
        draw_rect.width  = width;
        draw_rect.height = draw_height;

        memset(__this->buf1, 0, draw_rect.width * draw_rect.height * 2);

        jlgpu_set_task_list_out_buf(__this->gpu_task_head,  __this->buf1, &draw_rect, 0, 0);
        jlgpu_task_list_run(__this->gpu_task_head);
        /* jlgpu_dump_task_head(__this->gpu_task_head); */


        if (!i) {
            /* 开始推屏时使用 kistart */
            lcd_draw_kistart(__this->buf1, draw_rect.left, draw_rect.left + draw_rect.width - 1, draw_rect.top, draw_rect.top + draw_rect.height - 1);
            lcd_wait_busy();
        } else {
            /* 之后推屏时使用 continue 续传 */
            lcd_draw_continue(__this->buf1, draw_rect.left, draw_rect.left + draw_rect.width - 1, draw_rect.top, draw_rect.top + draw_rect.height - 1);
            lcd_wait_busy();
        }
    }

    lcd_wait_busy();
    //将申请的内存进行释放
    /* if(img->clut_tab){ */
    /* free(img->clut_tab); */
    /* img->clut_tab = NULL; */
    /* } */
    if (__this->buf1) {
        free(__this->buf1);
        __this->buf1 = NULL;
    }
    if (__this->buf2) {
        free(__this->buf2);
        __this->buf2 = NULL;
    }
}

